"""Cut each detected match out of the session and write a per-match bundle.

  <out>/<session>/
      session.json
      m01_defeat_escort_grimsvotn/
          match.mp4            stream copy, no re-encode (GOP is 0.5 s, so cuts land within 0.5 s)
          match.json           boundaries, result, map, TAB timestamps (in match-clip time too)
          events.json          deaths (killer), final blows (victim), deployables destroyed; after `owcoach events`
          scoreboard_final.jpg full-res final TAB scoreboard (if you pressed TAB)
          summary.jpg          full-res post-match Summary (hero, E/A/D, damage, healing, mitigation)
          rank.jpg             competitive only: rank + progress after the match
          sheet.jpg            contact sheet, one thumbnail every ~10 s
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import time
import tempfile
import unicodedata
from pathlib import Path

from .config import session_dir, session_name
from .scan import grab_frame
from .sheet import contact_sheets


def _slug(s: str | None) -> str:
    if not s:
        return ""
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def match_dirname(m: dict) -> str:
    parts = [f"m{m['n']:02d}", m.get("result") or "unknown", m.get("mode"), _slug(m.get("map"))]
    return "_".join(p for p in parts if p)


PS1_HEAD = r"""# Generated by owcoach. Cuts each match out of the session recording (stream copy, no
# re-encode -- takes seconds). Run from anywhere:  powershell -ExecutionPolicy Bypass -File cut_matches.ps1
$ErrorActionPreference = 'Stop'
if (-not (Get-Command ffmpeg -ErrorAction SilentlyContinue)) {
    Write-Host 'ffmpeg not found on PATH. Install it with:  winget install Gyan.FFmpeg' -ForegroundColor Yellow
    exit 1
}
"""

PS1_BODY = r"""foreach ($j in $jobs) {
    $out = Join-Path $PSScriptRoot (Join-Path $j.dir 'match.mp4')
    if (Test-Path $out) { Write-Host "skip  $($j.dir) (exists)"; continue }
    Write-Host "cut   $($j.dir)"
    & ffmpeg -hide_banner -loglevel error -y -ss $j.ss -i $src -t $j.t `
        -map '0:v:0' -map '0:a?' -c copy -avoid_negative_ts make_zero -movflags +faststart $out
    if ($LASTEXITCODE -ne 0) { throw "ffmpeg failed on $($j.dir)" }
}
Write-Host 'done'
"""


def write_cut_script(sdir: Path, video: Path, jobs: list[tuple[str, float, float]]) -> Path:
    """PowerShell cutter that runs on the machine that owns the recording.

    The recording's path is written relative to the script when both are on one drive, so the
    pair can be moved together; otherwise absolute.
    """
    try:
        rel = Path(os.path.relpath(video, sdir))
        src = f"Join-Path $PSScriptRoot '{str(rel).replace('/', chr(92))}'"
    except ValueError:            # different drives
        src = f"'{video}'"
    lines = [PS1_HEAD, f"$src = {src}", "$jobs = @("]
    for i, (d, ss, dur) in enumerate(jobs):
        comma = "," if i < len(jobs) - 1 else ""
        lines.append(f"    @{{ dir = '{d}'; ss = '{ss:.3f}'; t = '{dur:.3f}' }}{comma}")
    lines += [")", PS1_BODY]
    out = sdir / "cut_matches.ps1"
    out.write_text("\r\n".join("\r\n".join(lines).splitlines()) + "\r\n", encoding="utf-8-sig")
    return out


def split(cache: Path, out_root: Path | None = None, pad: float = 3.0,
          dry_run: bool = False, cut: str = "here") -> list[Path]:
    """cut: 'here' runs ffmpeg now, 'script' writes cut_matches.ps1 instead, 'none' skips."""
    sess = json.loads((cache / "matches.json").read_text())
    ev_path = cache / "events.json"
    evs = {e["n"]: e for e in json.loads(ev_path.read_text())["matches"]} if ev_path.exists() else {}
    video = Path(sess["video"])
    sdir = out_root / session_name(video) if out_root else session_dir(video)
    sdir.mkdir(parents=True, exist_ok=True)
    paths, jobs = [], []
    for m in sess["matches"]:
        d = sdir / match_dirname(m)
        d.mkdir(exist_ok=True)
        ss = max(0.0, m["start"] - pad)
        to = min(sess["duration"], m["end"] + pad)
        clip = d / "match.mp4"
        cmd = ["ffmpeg", "-hide_banner", "-nostdin", "-loglevel", "error", "-y",
               "-ss", f"{ss:.3f}", "-i", str(video), "-t", f"{to - ss:.3f}",
               "-map", "0:v:0", "-map", "0:a?", "-c", "copy",
               "-avoid_negative_ts", "make_zero", "-movflags", "+faststart", str(clip)]
        if dry_run:
            print(" ".join(f'"{c}"' if " " in c else c for c in cmd))
            continue
        jobs.append((d.name, ss, to - ss))
        # a clip cut for different boundaries would shift every clip-relative timestamp
        prev = json.loads((d / "match.json").read_text()) if (d / "match.json").exists() else {}
        stale = clip.exists() and (abs(prev.get("clip_offset", -1) - round(ss, 3)) > 0.01
                                   or abs(prev.get("clip_duration", to - ss) - (to - ss)) > 0.01)
        if cut == "here" and (stale or not clip.exists()):
            tmp = d / "match.part.mp4"
            subprocess.run(cmd[:-1] + [str(tmp)], check=True)
            for attempt in range(20):      # Windows: a scanner or indexer can hold the fresh file for a moment
                try:
                    tmp.replace(clip)
                    break
                except PermissionError:
                    if attempt == 19:
                        raise
                    time.sleep(0.5)
        # stills are cheap (one keyframe seek each), so always refresh them
        if m.get("final_tab_t") is not None:
            grab_frame(cache, m["final_tab_t"], d / "scoreboard_final.jpg")
        for key, name in (("summary_t", "summary.jpg"), ("rank_t", "rank.jpg")):
            if m.get(key) is not None:
                grab_frame(cache, m[key], d / name)
        with tempfile.TemporaryDirectory() as td:
            sheets = contact_sheets(cache, Path(td), every=20, cols=10, rows=12,
                                    tile_w=192, start=m["start"], end=m["end"])
            for old in d.glob("sheet*.jpg"):
                old.unlink()
            for i, sp in enumerate(sheets):
                shutil.copy(sp, d / ("sheet.jpg" if i == 0 else f"sheet_{i}.jpg"))
        meta = {**m, "session_video": str(video), "clip_offset": round(ss, 3), "clip_duration": round(to - ss, 3),
                "tab_times_clip": [round(x - ss, 2) for x in m.get("tab_times", [])],
                "heroes": [{**h, "from_clip": round(h["from"] - ss, 2), "to_clip": round(h["to"] - ss, 2)}
                           for h in m.get("heroes", [])]}
        (d / "match.json").write_text(json.dumps(meta, indent=1))
        if m["n"] in evs:
            def clip(e):   # every session timestamp ("t", "ready_t", ...) gets a clip-relative twin
                return {**e, **{f"{k}_clip": round(x - ss, 2) for k, x in e.items()
                                if (k == "t" or k.endswith("_t")) and isinstance(x, (int, float))}}
            ev = {k: [clip(e) for e in v] if isinstance(v, list) else v for k, v in evs[m["n"]].items()}
            (d / "events.json").write_text(json.dumps(ev, indent=1))
        m["dir"] = d.name            # relative to the session folder, so the library can move
        paths.append(d)
    if not dry_run:
        (sdir / "session.json").write_text(json.dumps(sess, indent=1))
        if cut == "script":
            paths.append(write_cut_script(sdir, video, jobs))
    return paths
